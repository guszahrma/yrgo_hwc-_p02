#define DAISY_SEED_HEADER_A9 DAISY_SEED_HEADER_D24
#define DAISY_SEED_HEADER_A10 DAISY_SEED_HEADER_D25
#define DAISY_SEED_HEADER_A11 DAISY_SEED_HEADER_D28

#endif /* DAISY_SEED_HEADER_H_ */
