#define DAISY_SEED_HEADER_D11 11 /* pin 12 = PB8 */
#define DAISY_SEED_HEADER_D12 12 /* pin 13 = PB9 */
#define DAISY_SEED_HEADER_D13 13 /* pin 14 = PB6 */
#define DAISY_SEED_HEADER_D14 14 /* pin 15 = PB7 */
